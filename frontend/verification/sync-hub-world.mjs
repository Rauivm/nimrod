// Deployable JS for Node 20, generated from the exact pure world used by Pixi.
// --write is explicit; normal verification never silently repairs drift.
import fs from 'node:fs/promises';
import ts from 'typescript';
const directory = new URL('../../backend/src/services/socialHub/world/', import.meta.url);
if (process.argv.includes('--write')) await fs.mkdir(directory, { recursive: true });
for (const name of ['Navigation', 'ExplorerMovement', 'tavernMap']) {
  const source = await fs.readFile(new URL(`../src/features/social-hub/world/${name}.ts`, import.meta.url), 'utf8');
  const { outputText } = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } });
  const expected = '// Generated by frontend/verification/sync-hub-world.mjs. Do not edit.\n' + outputText;
  const file = new URL(`${name}.js`, directory);
  if (process.argv.includes('--write')) await fs.writeFile(file, expected);
  else if ((await fs.readFile(file, 'utf8')).replaceAll('\r\n', '\n') !== expected) throw Error(`Regenerate authoritative world: ${name}`);
}
