import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { mkdir } from 'node:fs/promises';
await mkdir(new URL('../artifacts/', import.meta.url), { recursive: true });
const require = createRequire(new URL('../../../frontend/package.json', import.meta.url));
const { chromium } = require('playwright');
const base = process.env.NIMROD_FRONTEND_TEST_URL || 'http://127.0.0.1:5190';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const errors = [];
let userId = '00000000-0000-4000-8000-000000000001';
let characters = [];
let launchFails = true;
const active = { id: '00000000-0000-4000-8000-000000000010', name: 'Viajante de Teste', active: true, dead: false, retired: false, level: 1 };
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.addInitScript(() => localStorage.setItem('lgpd_seen', 'true'));
  await context.route('**/api/**', async route => {
    const url = new URL(route.request().url());
    let body = [];
    let status = 200;
    if (url.pathname === '/api/me') body = { id: userId, displayName: 'Conta de Teste', role: 'PLAYER' };
    if (url.pathname === '/api/me/characters') body = characters;
    if (url.pathname === '/api/mana/launch') {
      assert.deepEqual(route.request().postDataJSON(), { character_id: active.id });
      status = launchFails ? 503 : 200;
      body = launchFails ? { error: 'Taverna temporariamente indisponível' } : { url: 'http://localhost:5184/#nimrod=fixture-ticket' };
    }
    if (url.pathname === '/api/world/calendar') status = 503;
    await route.fulfill({ status, contentType: 'application/json', body: JSON.stringify(body) });
  });
  // Stub only the game document; this suite never redeems a ticket or writes local data.
  await context.route('http://localhost:5184/**', route => route.fulfill({ contentType: 'text/html', body: '<p>Game navigation fixture</p>' }));
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  const heading = () => page.getByRole('heading', { name: 'Seu próximo encontro começa aqui.' });
  await page.goto(base);
  await heading().waitFor();
  await page.screenshot({ path: fileURLToPath(new URL('../artifacts/experience-desktop.png', import.meta.url)) });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.locator('.experience-options').evaluate(node => node.getBoundingClientRect().right <= innerWidth));
  await page.screenshot({ path: fileURLToPath(new URL('../artifacts/experience-mobile.png', import.meta.url)), fullPage: true });
  await page.getByRole('button', { name: 'Continuar no modo clássico' }).click();
  await page.getByRole('heading', { name: '📜 Taverna', exact: true }).waitFor();
  await page.reload();
  await page.getByRole('heading', { name: '📜 Taverna', exact: true }).waitFor();
  await page.getByRole('link', { name: 'Modo Jogo', exact: true }).click();
  await page.getByRole('link', { name: 'Vincule um personagem no Perfil.' }).waitFor();
  characters = [active, { ...active, id: 'inactive', active: false }, { ...active, id: 'dead', dead: true }, { ...active, id: 'retired', retired: true }];
  await page.getByRole('button', { name: 'Atualizar personagens' }).click();
  await page.getByRole('button', { name: 'Entrar como Viajante de Teste' }).waitFor();
  assert.equal(await page.locator('#lobby-character option').count(), 2);
  await page.getByRole('button', { name: 'Entrar como Viajante de Teste' }).click();
  await page.getByRole('alert').filter({ hasText: 'Taverna temporariamente indisponível' }).waitFor();
  assert.equal(context.pages().length, 1, 'Failed launch closes its empty tab');
  launchFails = false;
  const [popup] = await Promise.all([context.waitForEvent('page'), page.getByRole('button', { name: 'Entrar como Viajante de Teste' }).click()]);
  await popup.waitForURL('http://localhost:5184/**');
  await popup.waitForLoadState();
  const launchUrl = new URL(popup.url());
  assert.equal(launchUrl.searchParams.get('nimrod_origin'), base);
  assert.equal(launchUrl.hash, '#nimrod=fixture-ticket');
  assert.equal(await popup.evaluate(() => window.opener), null);
  await popup.close();
  await page.goto(base);
  await page.waitForURL('**/lobby');
  await page.getByRole('link', { name: 'Ver mural de aventuras' }).click();
  await page.getByRole('heading', { name: '📋 Quadro de Avisos' }).waitFor();
  await page.goto(base + '/?experience=classic');
  await page.getByRole('heading', { name: '📜 Taverna', exact: true }).waitFor();
  await page.reload();
  await page.getByRole('heading', { name: '📜 Taverna', exact: true }).waitFor();
  userId = '00000000-0000-4000-8000-000000000002';
  await page.goto(base);
  await heading().waitFor();
  await page.evaluate(() => localStorage.setItem('nimrod:experience:00000000-0000-4000-8000-000000000002', 'invalid'));
  await page.reload();
  await heading().waitFor();
  userId = '00000000-0000-4000-8000-000000000001';
  await page.reload();
  await page.getByRole('heading', { name: '📜 Taverna', exact: true }).waitFor();
  await page.addInitScript(() => {
    const get = Storage.prototype.getItem, set = Storage.prototype.setItem;
    Storage.prototype.getItem = function(key) { if (key.startsWith('nimrod:experience:')) throw new Error('blocked'); return get.call(this, key); };
    Storage.prototype.setItem = function(key, value) { if (key.startsWith('nimrod:experience:')) throw new Error('blocked'); return set.call(this, key, value); };
  });
  await page.reload();
  await heading().waitFor();
  await page.getByRole('button', { name: 'Continuar no modo clássico' }).click();
  await page.getByRole('heading', { name: '📜 Taverna', exact: true }).waitFor();
  assert.deepEqual(errors, []);
  console.log('EXPERIENCE_ENTRY_PASS: classic/game, reload, account isolation, invalid/blocked storage, empty/eligible characters, failed launch/retry, opaque launch URL, existing mission board, desktop/mobile');
  await context.close();
} finally { await browser.close(); }
